def reference_integration(P, years, seed_idx, t0_idx, rule=REF_RULE):
    """`tau` and the flow counts at one (seed, t0) from `scipy.solve_ivp` at
    tight tolerance, integrating the 6x6 Phi ODE and its accumulators directly
    off `coeff_path`.

    Independent of the exponential-midpoint scheme in `zinc_circ_lab`: a
    different quadrature, a different step-size controller and a different
    evaluation of A(t).  Only the closed-form tail is shared, and that term is
    exact.
    """
    from scipy.integrate import solve_ivp

    Pn = P[seed_idx:seed_idx + 1]
    t0 = years[t0_idx]
    _, t_switch = L.coeff_path(Pn, years, np.array([years[-1]]), rule=rule)
    nf = len(L.FLOW_NAMES)

    def rhs(u, z):
        Pt, _ = L.coeff_path(Pn, years, np.array([t0 + u]), rule=rule)
        A = L.assemble_from_params(Pt)[0, 0]
        c = {k: v[0] for k, v in L.flow_rows(A[None]).items()}
        Phi = z[:36].reshape(6, 6)
        out = np.empty_like(z)
        out[:36] = (A @ Phi).ravel()
        out[36:42] = np.ones(6) @ Phi
        for j, k in enumerate(L.FLOW_NAMES):
            out[42 + 6 * j: 48 + 6 * j] = c[k] @ Phi
        return out

    z0 = np.zeros(36 + 6 * (1 + nf))
    z0[:36] = np.eye(6).ravel()
    U = float(t_switch - t0)
    if U > 0:
        sol = solve_ivp(rhs, (0.0, U), z0, method="LSODA",
                        rtol=1e-11, atol=1e-13, dense_output=False)
        z = sol.y[:, -1]
    else:
        z = z0
    Phi = z[:36].reshape(6, 6)
    Pe, _ = L.coeff_path(Pn, years, np.array([t_switch + 1.0]), rule=rule)
    Ae = L.assemble_from_params(Pe)[0, 0]
    Ne = L.fundamental(Ae[None], on_singular="nan")[0]
    ce = {k: v[0, 0] for k, v in L.flow_rows(Ae[None, None]).items()}
    tau = z[36:42] + np.ones(6) @ Ne @ Phi
    counts = {k: z[42 + 6 * j: 48 + 6 * j] + ce[k] @ Ne @ Phi
              for j, k in enumerate(L.FLOW_NAMES)}
    return tau, counts


