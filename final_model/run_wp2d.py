def indicator_table(frozen, nonauto, years, seeds):
    """Median/IQR across seeds, per (year, start stock, indicator, form)."""
    rows = []
    items = [("tau_FD", frozen["tau"], {r: v["tau"] for r, v in nonauto.items()})]
    for k in L.FLOW_NAMES:
        items.append((k, frozen["counts"][k],
                      {r: v["counts"][k] for r, v in nonauto.items()}))
    for name, fr, na in items:
        for i in range(6):
            for ti, y in enumerate(years):
                q = np.nanpercentile(fr[:, ti, i], [25, 50, 75])
                rows.append(dict(indicator=name, start_stock=STATE[i],
                                 year=float(y), form="frozen", rule="",
                                 median=q[1], q1=q[0], q3=q[2],
                                 n_seeds=int(np.isfinite(fr[:, ti, i]).sum())))
                for rule, v in na.items():
                    q = np.nanpercentile(v[:, ti, i], [25, 50, 75])
                    rows.append(dict(
                        indicator=name, start_stock=STATE[i], year=float(y),
                        form="nonautonomous", rule=rule,
                        median=q[1], q1=q[0], q3=q[2],
                        n_seeds=int(np.isfinite(v[:, ti, i]).sum())))
    return pd.DataFrame(rows)


def discrepancy_table(frozen, nonauto, years):
    """The headline object: non-autonomous minus frozen, seed-paired.

    Reported in native units and as a fraction of the frozen value, with a
    Hodges-Lehmann interval over the 35 seeds (project convention: HL
    intervals, not significance tests).
    """
    rows = []
    items = [("tau_FD", frozen["tau"], {r: v["tau"] for r, v in nonauto.items()})]
    for k in L.FLOW_NAMES:
        items.append((k, frozen["counts"][k],
                      {r: v["counts"][k] for r, v in nonauto.items()}))
    for name, fr, na in items:
        for rule, v in na.items():
            for i in range(6):
                for ti, y in enumerate(years):
                    dif = v[:, ti, i] - fr[:, ti, i]
                    rel = dif / fr[:, ti, i]
                    h = L.hodges_lehmann(dif)
                    hr = L.hodges_lehmann(rel)
                    rows.append(dict(
                        indicator=name, rule=rule, start_stock=STATE[i],
                        year=float(y),
                        frozen_median=float(np.nanmedian(fr[:, ti, i])),
                        nonauto_median=float(np.nanmedian(v[:, ti, i])),
                        abs_diff_hl=h["hl"], abs_diff_lo=h["lo"],
                        abs_diff_hi=h["hi"],
                        rel_diff_hl=hr["hl"], rel_diff_lo=hr["lo"],
                        rel_diff_hi=hr["hi"], n_seeds=h["n"]))
    return pd.DataFrame(rows)


