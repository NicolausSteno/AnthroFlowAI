def check(verbose=True, n_sub_ref=192):
    """Everything that must hold before any WP-11e/f number is believed."""
    import zinc_colloc_v5 as v5

    res = {}
    integrity_check()
    install(v5)
    cfg = load_anchor_config()
    ctx = S.driver_context(cfg)

    if verbose:
        print("--- resolved drivers (by name, never by position) ---")
        for short, name in S.DRIVER_ALIASES.items():
            print(f"  {short:9s} -> {name!r}  "
                  f"[col {list(ctx['exog_cols']).index(name)}]")
        n_ex = len(ctx["exog_cols"])
        orders = len(cfg.get("exog_feature_orders", (0, 1)))
        print(f"  exog columns = {n_ex}, feature orders = {orders}, "
              f"input_dim = {1 + 4 + n_ex * orders}")
        print(f"  (CLAUDE.md rule 2 asserts input_dim == 23; the anchor_v4 "
              f"config gives {1 + 4 + n_ex * orders} — SCHEMA §9 flag 1, "
              f"still open)")

    # ---- 1. the cobweb solves and oscillates, and the delay sets the period
    sol = cobweb_solve(ctx)
    dp = dominant_period(sol)
    res["cobweb_period_ref_yr"] = dp["period_yr"]
    res["cobweb_period_ref_fft_yr"] = dp["period_fft_yr"]
    res["cobweb_cycles_in_record"] = dp["cycles_in_record"]
    res["cobweb_rms_log_price"] = dp["rms_log"]
    res["cobweb_finite"] = bool(np.all(np.isfinite(sol["P"])))

    # grid convergence of the delayed solve
    sol2 = cobweb_solve(ctx, n_sub=2 * S.N_SUB)
    i2 = np.searchsorted(sol2["t"], sol["t"])
    res["cobweb_grid_rel"] = float(np.max(np.abs(sol2["osc"][i2] - sol["osc"]))
                                   / max(np.std(sol["osc"]), 1e-12))

    # shortening the lead time must shorten the cycle (Ch. 3 Sec. 5.1)
    per = {}
    for te in CH3_TAU_PUBLISHED:
        per[te] = dominant_period(cobweb_solve(ctx, tau_E=te))["period_yr"]
    # The zero-crossing period is quantised at `2 x span / n`, and a
    # multi-decadal cycle makes only two to six crossings in a 39-yr record,
    # so the estimator resolves the period to about one bin.  Monotonicity is
    # therefore only testable where the bins are far enough apart; below
    # tau_E = 4 yr it is not resolvable and is reported, not gated.
    _tail = [t for t in CH3_TAU_PUBLISHED if t >= 4.0]
    res["period_nondecreasing_tau_ge_4"] = bool(
        all(per[a] <= per[b] + 1e-9 for a, b in zip(_tail, _tail[1:])))
    res["periods_by_tau"] = {str(k): float(v) for k, v in per.items()}
    # The floor: no lead time in or below the paper's range makes the Ch. 3
    # oscillation sub-annual.  This is a finding, checked as an invariant.
    res["min_period_over_tau_yr"] = float(min(
        dominant_period(cobweb_solve(ctx, tau_E=te))["period_yr"]
        for te in tuple(CH3_TAU_SHORT) + tuple(CH3_TAU_PUBLISHED)))
    res["ch3_never_subannual"] = bool(res["min_period_over_tau_yr"] > 1.0)

    # ---- 2. the Fourier bridge reconstructs the cobweb
    for arm in MARKET_ARMS:
        a = arm_solution(ctx, arm)
        res[f"fourier_rel_l2_{arm}"] = a["fourier"]["rel_l2"]
        res[f"period_{arm}_yr"] = a["period"]["period_yr"]
        res[f"rms_logP_{arm}"] = float(np.std(a["sol"]["osc"]) * a["amplitude_scale"])
    res["fourier_ok"] = bool(all(res[f"fourier_rel_l2_{a}"] <= FOURIER_TOL
                                 for a in MARKET_ARMS))

    # ---- 3. spectral operators against their closed forms
    #   the boxcar annihilates harmonics of the window and attenuates the rest
    res["sinc_null_1yr"] = float(sinc_gain(1.0, 1.0))
    res["sinc_null_2yr"] = float(sinc_gain(2.0, 1.0))
    res["sinc_135"] = float(sinc_gain(1.35, 1.0))
    #   measured on a pure tone integrated over unit windows
    t = np.linspace(0.0, 40.0, 40 * 96 + 1)
    for f in (1.0, 1.35, 2.70):
        y = np.sin(2 * np.pi * f * t + 0.7)
        c = np.concatenate([[0.0], np.cumsum(0.5 * (y[1:] + y[:-1]) * (t[1] - t[0]))])
        k = np.arange(0, t.size, 96)
        win = (c[k[1:]] - c[k[:-1]])              # unit-window integrals
        mid = 0.5 * (t[k[1:]] + t[k[:-1]])
        got = project_amplitude(mid, win, f)["amp"]
        res[f"boxcar_gain_meas_f{f}"] = float(got)
        res[f"boxcar_gain_form_f{f}"] = float(sinc_gain(f, 1.0))
    #   point sampling folds instead of annihilating
    res["alias_1yr_point"] = float(alias_freq(1.0, 1.0))
    res["alias_135_point"] = float(alias_freq(1.35, 1.0))
    res["alias_270_point"] = float(alias_freq(2.70, 1.0))

    # ---- 4. Jensen gap in closed form against a numerical average
    a = 0.4
    u = np.linspace(0.0, 2 * np.pi, 20001)
    num = np.log(np.trapezoid(np.exp(a * np.sin(u)), u) / (2 * np.pi))
    res["jensen_gap_rel_err"] = float(abs(num - jensen_log_bias(a))
                                      / max(abs(num), 1e-30))

    # ---- 5. real-data coarsening is an exact re-aggregation
    c1 = coarsen_real(1)
    raw_alpha = None
    loader = S._ORIG_LOADER or v5.load_zinc_data
    raw = loader(cfg["xlsx_path"], extra_exog_cols=cfg.get("extra_exog_cols"))
    raw_alpha = np.asarray(raw["alpha_obs"], float)
    m = np.isfinite(raw_alpha) & np.isfinite(c1["alpha_obs"])
    res["coarsen_real_d1_vs_loader"] = float(
        np.max(np.abs(c1["alpha_obs"][m] - raw_alpha[m])))
    c2 = coarsen_real(2)
    # flow integrals at Delta=2 must equal the sum of the two annual ones
    res["coarsen_real_flow_sum"] = float(np.max(np.abs(
        c2["F_int"] - (c1["F_int"][0::2][:c2["F_int"].shape[0]]
                       + c1["F_int"][1::2][:c2["F_int"].shape[0]]))))

    # ---- 6. cross-channel contamination in `bias_cell`
    #   driving all four channels at once vs one at a time, at the largest
    #   amplitude on the grid: the gap bounds the shared-trajectory term.
    cells_all, _ = bias_cell(ctx, freq=1.35, amp=BIAS_AMPS[-1], phase=0.0)
    cells_one, _ = bias_cell(ctx, freq=1.35, amp=BIAS_AMPS[-1], phase=0.0,
                             channels=["alpha_win"])
    res["bias_cross_channel_max_log"] = float(np.max(np.abs(
        cells_all["alpha_win"]["total"] - cells_one["alpha_win"]["total"])))

    if verbose:
        print("\n--- zinc_market_lab check ---")
        for k, v in res.items():
            print(f"  {k:34s} {v}")
        print(f"\n  patches installed: {S.PATCHES}")
    return res


