def load(path=A_NPZ):
    if not os.path.exists(path):
        raise SystemExit(f"{path} not found — run run_wp2a.py first")
    d = np.load(path, allow_pickle=True)
    return d, hashlib.md5(open(path, "rb").read()).hexdigest()


