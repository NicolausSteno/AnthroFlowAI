    season, fc = market_season(sol, amplitude=scale, n_keep=spec["n_keep"])
    return dict(arm=arm, sol=sol, season=season, fourier=fc,
                amplitude_scale=scale, rms_logP=rms_ref,
                published=spec["published"],
                period=dominant_period(sol))


