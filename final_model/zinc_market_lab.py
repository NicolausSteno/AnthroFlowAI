# 6. real-data coarsening (WP-11b's observation-side arm)
# ===========================================================================
# WP-6b coarsens the *record* and refits; that is 528 fits and is not
# available.  What is available without a single fit is the coarsening of the
# **target**, on the real data, through the core's own operators — flows are
# additive over windows so an annual record aggregates exactly to Delta = 2,
# 5, 10, stocks are point-read at the retained nodes, and `alpha_obs` is
# rebuilt by `_build_empirical_alphas` at each width.  The same statistic is
# computable on the twin, where the truth is known.  Comparing the two curves
# is a like-for-like check of whether the twin reproduces the real record's
# response to coarsening on the observation side.
def coarsen_real(delta, *, cfg=None, start_aligned=True):
    """The real dataset re-expressed at window width `delta` (years).

    `delta` must be an integer number of years: the real record is annual and
    a coarser window is an exact sum of annual flow integrals.  Stocks are
    point-read at the retained year boundaries.  Returns the coarsened
    `alpha_obs` together with the annual reference aggregated the same way,
    so the two are directly comparable.
    """
    import zinc_colloc_v5 as v5

    step = int(round(float(delta)))
    if abs(step - float(delta)) > 1e-9 or step < 1:
        raise ValueError(f"delta={delta} is not a whole number of years; the "
                         f"real record is annual and cannot be refined")
    cfg = dict(cfg or load_anchor_config())
    loader = S._ORIG_LOADER or v5.load_zinc_data
    raw = loader(cfg["xlsx_path"], extra_exog_cols=cfg.get("extra_exog_cols"))

    yrs = np.asarray(raw["years"], float).ravel()
    S_obs = np.asarray(raw["stocks_obs"], float)
    F_obs = np.asarray(raw["flows_obs"], float)            # (T-1, n_obs_flows)
    pred_idx = list(np.asarray(raw["flow_obs_to_pred_idx"], int))

    # the four alpha parent flows, in v5.FLOW_NAMES indices 1..4
    cols = [pred_idx.index(j) for j in (1, 2, 3, 4)]
    Fp = F_obs[:, cols]                                     # (T-1, 4)

    nW = (yrs.size - 1) // step
    keep = np.arange(nW + 1) * step
    if not start_aligned:
        keep = keep + ((yrs.size - 1) - nW * step)
    t_nodes = yrs[keep]
    S_pt = S_obs[keep]
    F_int = np.stack([Fp[keep[i]:keep[i + 1]].sum(axis=0) for i in range(nW)])

    F_for_alpha = np.zeros((t_nodes.size, 4))
    F_for_alpha[1:] = F_int
    alpha = v5._build_empirical_alphas(t_nodes, S_pt, F_for_alpha)
    return dict(years=t_nodes, delta=float(step), alpha_obs=alpha,
                stocks_obs=S_pt, F_int=F_int, keep=keep,
                alpha_names=list(v5.ALPHA_NAMES))


def coarsen_twin(dense, ctx, delta):
    """The same coarsening applied to the twin, with the truth alongside."""
    samp = S.sample(dense, float(delta), ctx, noise_scale=0.0)
    return dict(years=samp["years"], delta=float(delta),
                alpha_obs=samp["alpha_obs"], stocks_obs=samp["stocks_obs"],
                F_int=samp["F_int"])


