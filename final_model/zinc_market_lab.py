def fourier_components(t, y, *, n_keep=N_FOURIER_DEFAULT, t0=None):
    """Project `y(t)` onto `sum_k a_k sin(2 pi f_k (t - t0) + ph_k)`.

    A real DFT over the window, keeping the `n_keep` largest-amplitude
    non-zero bins.  Returns `(f, a, ph)` arrays and the relative L2 error of
    the truncated reconstruction, which is the number that has to be small
    before a twin built on this bridge means anything.
    """
    t = np.asarray(t, float).ravel()
    y = np.asarray(y, float).ravel()
    t0 = float(t[0] if t0 is None else t0)
    h = t[1] - t[0]
    n = y.size - 1                      # drop the duplicate endpoint
    yy = y[:n] - y[:n].mean()
    Y = np.fft.rfft(yy) / n
    f = np.fft.rfftfreq(n, d=h)
    amp = 2.0 * np.abs(Y)
    amp[0] = 0.0
    if n % 2 == 0:
        amp[-1] = np.abs(Y[-1])
    # rfft convention: y ~ sum amp_k * cos(2 pi f_k (t - t[0]) + angle(Y_k))
    # and cos(x) = sin(x + pi/2), so the sine phase is angle + pi/2.
    ph = np.angle(Y) + 0.5 * np.pi
    order = np.argsort(-amp)[:int(n_keep)]
    order = order[amp[order] > 0.0]
    fk, ak, pk = f[order], amp[order], ph[order]
    # phases are referenced to t[0]; shift to the requested t0
    pk = pk + 2.0 * np.pi * fk * (t[0] - t0)
    rec = np.zeros_like(t)
    for fi, ai, pi_ in zip(fk, ak, pk):
        rec += ai * np.sin(2.0 * np.pi * fi * (t - t0) + pi_)
    err = float(np.linalg.norm(rec - (y - y.mean()))
                / max(np.linalg.norm(y - y.mean()), 1e-30))
    return dict(f=fk, a=ak, phase=pk, rel_l2=err, recon=rec)


def market_season(sol, *, elasticity=None, amplitude=1.0,
                  n_keep=N_FOURIER_DEFAULT, t0=None, channels=None):
    """A `zinc_synth_lab` `season` list carrying the cobweb oscillation.

    `amplitude` rescales the whole waveform so the *shape and frequency* come
    from the delay system while the size is a stated design choice; setting it
    to 1.0 uses the cobweb's own realised log-price amplitude.
    """
    t0 = float(S.TRUTH["season_t0"] if t0 is None else t0)
    el = dict(MARKET_ELASTICITY if elasticity is None else elasticity)
    if channels is not None:
        el = {k: v for k, v in el.items() if k in channels}
    fc = fourier_components(sol["t"], sol["osc"], n_keep=n_keep, t0=t0)
    season = []
    for chan, e in el.items():
        for fi, ai, pi_ in zip(fc["f"], fc["a"], fc["phase"]):
            season.append((chan, float(fi), float(e * amplitude * ai),
                           float(pi_)))
    return season, fc


