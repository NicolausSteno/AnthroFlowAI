def gdp_growth(ctx):
    """Real GDP growth rate on the twin's annual grid, from the dataset.

    `r(t)` in Ch. 3 Eq. (21).  Resolved by explicit name through
    `zinc_synth_lab.DRIVER_ALIASES` (CLAUDE.md rule 2), never by position.
    """
    cols = list(ctx["exog_cols"])
    j = cols.index(S.DRIVER_ALIASES["GDP"])
    g = np.asarray(ctx["exog_values"][:, j], float)
    yrs = np.asarray(ctx["years"], float)
    r = np.zeros_like(g)
    r[1:] = np.diff(np.log(np.maximum(g, 1e-12))) / np.diff(yrs)
    r[0] = r[1]
    return yrs, r


def cobweb_solve(ctx, *, tau_E=None, tau_R=None, n_sub=S.N_SUB, params=None,
                 P0=None, Q0=None, E0=None, R0=None, hist_slope=0.0):
    """Integrate Ch. 3 Eqs. (18)-(21)/(24)-(25) on the twin's window.

    Fixed-step RK4 on the twin's own `n_sub`-per-year grid with linear
    interpolation of the history at the delayed arguments — the paper solves
    the same system with Hermite interpolation at the delays; the difference
    is O(h^2) against O(h^4) *in the delayed lookup only*, and `check()`
    measures the grid convergence rather than assuming it.

    The switched right-hand side (supply follows price when price is rising,
    and follows demand otherwise) is Eq. (24)'s discontinuity and is kept as
    written; it is what makes the cycle asymmetric.

    Returns `t, P, Q, E, R` plus the realised oscillation diagnostics.
    """
    p = dict(CH3)
    p.update(params or {})
    tau_E = float(p["tau_E"] if tau_E is None else tau_E)
    tau_R = float(p["tau_R"] if tau_R is None else tau_R)

    P0 = CH3_IC["P0"] if P0 is None else float(P0)
    Q0 = CH3_IC["Q0"] if Q0 is None else float(Q0)
    E0 = CH3_IC["E0"] if E0 is None else float(E0)
    R0 = CH3_IC["R0"] if R0 is None else float(R0)

    yrs, r_ann = gdp_growth(ctx)
    t = S.fine_grid(yrs, n_sub)
    h = 1.0 / float(n_sub)
    n = t.size

    # Pre-history: the delayed arguments reach back before t0, so the price
    # history is extended as a constant (Ch. 3's own "state variables
    # containing delays were assumed to be constant" initial condition).
    P = np.empty(n); Q = np.empty(n); E = np.empty(n); R = np.empty(n)
    P[0], Q[0], E[0], R[0] = P0, Q0, E0, R0

    def _hist_P(s, i_now):
        """P at time `s <= t[i_now]`, linearly interpolated on the solved
        prefix; constant extrapolation with slope `hist_slope` before t0."""
        if s <= t[0]:
            return P0 * np.exp(hist_slope * (s - t[0]))
        k = min(int((s - t[0]) / h), i_now)
        if k >= i_now:
            return P[i_now]
        w = (s - t[k]) / h
        return (1.0 - w) * P[k] + w * P[k + 1]

    def _gp(s, i_now):
        """`(1/P) dP/dt` at the delayed time `s` — Ch. 3's `g_p`."""
        a = _hist_P(s - 0.5 * h, i_now)
        b = _hist_P(s + 0.5 * h, i_now)
        m = _hist_P(s, i_now)
        return (b - a) / h / max(m, 1e-12)

    r_of = lambda s: float(np.interp(s, yrs, r_ann))

    def deriv(i, s, P_i, Q_i, E_i, R_i):
        Sup = E_i + R_i
        dP = p["c"] * P_i * (Q_i - Sup) / max(Q_i, 1e-12) + p["delta"]
        dQ = (p["eta"] / max(P_i, 1e-12)) * r_of(s) * Q_i
        gE = _gp(s - tau_E, i)
        gR = _gp(s - tau_R, i)
        dE = p["k_E"] * gE * E_i if gE > 0.0 else p["k_E"] * p["z_E"] * dQ
        dR = p["k_R"] * gR * R_i if gR > 0.0 else p["k_R"] * p["z_R"] * dQ
        return dP, dQ, dE, dR

    for i in range(n - 1):
        y = (P[i], Q[i], E[i], R[i])
        k1 = deriv(i, t[i], *y)
        y2 = tuple(v + 0.5 * h * d for v, d in zip(y, k1))
        k2 = deriv(i, t[i] + 0.5 * h, *y2)
        y3 = tuple(v + 0.5 * h * d for v, d in zip(y, k2))
        k3 = deriv(i, t[i] + 0.5 * h, *y3)
        y4 = tuple(v + h * d for v, d in zip(y, k3))
        k4 = deriv(i, t[i] + h, *y4)
        P[i + 1], Q[i + 1], E[i + 1], R[i + 1] = [
            v + (h / 6.0) * (a + 2 * b + 2 * c + d)
            for v, a, b, c, d in zip(y, k1, k2, k3, k4)]
        P[i + 1] = max(P[i + 1], 1e-9)
        E[i + 1] = max(E[i + 1], 1e-12)
        R[i + 1] = max(R[i + 1], 1e-12)
        Q[i + 1] = max(Q[i + 1], 1e-12)

    logP = np.log(P)
    # Detrend: the market *oscillation* is what annual observation is being
    # asked about, not the secular price trend, which the drivers already
    # carry.  A straight line in log price is removed and reported.
    A = np.column_stack([np.ones_like(t), t - t[0]])
    beta, *_ = np.linalg.lstsq(A, logP, rcond=None)
    osc = logP - A @ beta

    if not np.all(np.isfinite(P)):
        raise FloatingPointError(
            f"cobweb diverged at tau_E={tau_E}, c={p['c']}: the switched RHS "
            f"of Eq. (24) is stiff in the explosive regime and needs a finer "
            f"grid than n_sub={n_sub}")

    return dict(t=t, P=P, Q=Q, E=E, R=R, log_price=logP, osc=osc,
                trend=beta, tau_E=tau_E, tau_R=tau_R, n_sub=int(n_sub),
                params={k: float(v) for k, v in p.items()},
                ic=dict(P0=P0, Q0=Q0, E0=E0, R0=R0))


def dominant_period(sol, *, f_lo=1.0 / 40.0, f_hi=None):
    """Period of the detrended log-price oscillation, two ways.

    The record is only ~39 yr, so a multi-decadal cobweb completes one or two
    cycles in it and an FFT peak lands on a record-length harmonic whether or
    not the oscillation is real.  The **zero-crossing** period is therefore
    reported alongside and is the one quoted: `2 x span / n_crossings` needs
    no bin alignment.  They agree to within a bin whenever both are meaningful
    and disagree loudly when the FFT is reading its own grid.
    """
    t, y = sol["t"], sol["osc"]
    h = t[1] - t[0]
    f_hi = 0.5 / h if f_hi is None else f_hi
    Y = np.fft.rfft(y - y.mean())
    f = np.fft.rfftfreq(y.size, d=h)
    p = np.abs(Y) ** 2
    m = (f >= f_lo) & (f <= f_hi)
    if not np.any(m):
        return dict(f_peak=np.nan, period_yr=np.nan, share=np.nan)
    k = np.argmax(np.where(m, p, -np.inf))
    sgn = np.sign(y - y.mean())
    nz = int(np.sum(sgn[1:] * sgn[:-1] < 0))
    span = float(t[-1] - t[0])
    per_zc = 2.0 * span / nz if nz > 0 else np.inf
    return dict(f_peak=float(f[k]),
                period_fft_yr=float(1.0 / f[k]) if f[k] > 0 else np.inf,
                period_yr=float(per_zc), n_crossings=nz,
                cycles_in_record=float(span / per_zc) if np.isfinite(per_zc) else 0.0,
                share=float(p[k] / max(p[m].sum(), 1e-30)),
                rms_log=float(np.std(y)))


