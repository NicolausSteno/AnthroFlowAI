    ref = cobweb_solve(ctx, n_sub=n_sub)                 # the reference case
    rms_ref = float(np.std(ref["osc"]))
    sol = (ref if arm == "mkt_ref" else
           cobweb_solve(ctx, tau_E=spec["tau_E"], tau_R=spec["tau_R"],
                        params=spec["params"], n_sub=n_sub))
