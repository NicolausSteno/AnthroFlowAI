def fig_circularity(frozen, nonauto, years, mask_test, path):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    t0 = float(years[np.asarray(mask_test, bool)][0])
    fig, axes = plt.subplots(2, 2, figsize=(12.0, 8.0))

    def band(ax, X, colour, label, ls="-"):
        lo, med, hi = np.nanpercentile(X, [25, 50, 75], axis=0)
        ax.fill_between(years, lo, hi, color=colour, alpha=0.18, lw=0)
        ax.plot(years, med, color=colour, lw=1.8, ls=ls, label=label)

    # (a) technological lifetime
    ax = axes[0, 0]
    band(ax, frozen["tau"][:, :, START], "k", r"frozen  $\tau^{fr}_1(t)$",
         ls="--")
    for rule, v in nonauto.items():
        band(ax, v["tau"][:, :, START], RULE_COL[rule],
             rf"non-autonomous, {rule}")
    ax.set_ylabel("yr")
    ax.set_title(r"(a) technological lifetime $\tau_{FD,1}$"
                 "\n     Ch2 Eq. frozen_time_circularity vs "
                 "Eq. nonautonomous_lifetime", loc="left", fontsize=9)
    ax.legend(fontsize=6.5, frameon=False, ncol=2)

    # (b) expected use episodes
    ax = axes[0, 1]
    band(ax, frozen["counts"]["use_entry"][:, :, START], "k",
         r"frozen  $\upsilon^{fr}_1(t)$", ls="--")
    for rule, v in nonauto.items():
        band(ax, v["counts"]["use_entry"][:, :, START], RULE_COL[rule], rule)
    ax.set_ylabel("expected entries into use")
    ax.set_title(r"(b) expected use count $\upsilon_1$"
                 "\n     Ch2 Eq. nonautonomous_use_count", loc="left",
                 fontsize=9)
    ax.legend(fontsize=6.5, frameon=False, ncol=2)

    # (c) the discrepancy, relative
    ax = axes[1, 0]
    for rule, v in nonauto.items():
        rel = (v["tau"][:, :, START] - frozen["tau"][:, :, START]) / \
            frozen["tau"][:, :, START]
        band(ax, 100 * rel, RULE_COL[rule], rf"$\tau$, {rule}")
    rel = (nonauto[REF_RULE]["counts"]["use_entry"][:, :, START]
           - frozen["counts"]["use_entry"][:, :, START]) / \
        frozen["counts"]["use_entry"][:, :, START]
    band(ax, 100 * rel, "#000000", rf"$\upsilon$, {REF_RULE}", ls=":")
    ax.axhline(0, color="k", lw=0.8)
    ax.set_ylabel("non-autonomous − frozen  (% of frozen)")
    ax.set_title("(c) the frozen-time approximation error", loc="left",
                 fontsize=9.5)
    ax.legend(fontsize=6.5, frameon=False, ncol=2)

    # (d) the two old-scrap routes
    ax = axes[1, 1]
    for k, c, lab in (("oldscrap_manufacture", COL[0],
                       r"$\Upsilon_{13}$  alpha_dr"),
                      ("oldscrap_metallurgy", COL[2],
                       r"$\Upsilon_{14}$  alpha_win")):
        band(ax, frozen["counts"][k][:, :, START], c, lab + "  frozen",
             ls="--")
        band(ax, nonauto[REF_RULE]["counts"][k][:, :, START], c,
             lab + "  non-aut.")
    ax.set_ylabel("expected old-scrap returns")
    ax.set_title(r"(d) the two Ch2 circularity routes, $\Upsilon_{13}$ vs "
                 r"$\Upsilon_{14}$", loc="left", fontsize=9.5)
    ax.legend(fontsize=6.5, frameon=False, ncol=2)

    for ax in axes.ravel():
        ax.axvline(t0, color=GREY, lw=0.9, ls=":")
        ax.spines[["top", "right"]].set_visible(False)
        ax.grid(lw=0.4, alpha=0.3)
        ax.set_xlabel(r"$t_0$  (year)")
    fig.suptitle("WP-2d  circularity indicators on the estimated A(t) — "
                 "anchor_v4, 35 seeds (median, IQR); "
                 "start stock = S_conc; dotted vline = held-out window",
                 fontsize=11, x=0.01, ha="left")
    fig.tight_layout(rect=(0, 0, 1, 0.95))
    fig.savefig(path, dpi=300)
    fig.savefig(path.replace(".png", ".pdf"))
    plt.close(fig)


