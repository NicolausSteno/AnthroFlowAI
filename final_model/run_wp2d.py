def main(argv=None):
    ap = argparse.ArgumentParser(
        description="WP-2d: frozen-time vs non-autonomous circularity")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--npz", default=A_NPZ)
    ap.add_argument("--out", default=OUT_DIR)
    ap.add_argument("--n-sub", type=int, default=N_SUB)
    args = ap.parse_args(argv)

    L.check(verbose=True)
    if args.check:
        return 0

    d, md5 = load(args.npz)
    A = np.asarray(d["A"], float)
    years = np.asarray(d["years"], float)
    seeds = np.asarray(d["seeds"], int)
    mu = np.asarray(d["mu_cohorts"], float)
    S, T = A.shape[:2]
    P = L.pack_params(d, mu)
    print(f"\nloaded {os.path.basename(args.npz)}  md5 {md5}")
    print(f"  A {A.shape}  seeds {S}  years {years[0]:.0f}-{years[-1]:.0f}")
    print(f"  A_FD(t) = A(t): the UDE has no landfill state, so the 6-state "
          f"IS Ch2's transient space")

    # --- frozen-time --------------------------------------------------------
    tau_fr, cnt_fr, N = L.frozen_indicators(A)
    frozen = dict(tau=tau_fr, counts=cnt_fr)
    print(f"\n--- frozen-time (Ch2 Eq. frozen_time_circularity) ---")
    print(f"  -A is an M-matrix at all {S*T} nodes: min N entry "
          f"{N.min():.3e} (must be >= 0), max spectral abscissa "
          f"{L.spectral_abscissa(A).max():+.5f} /yr")
    for i in (0, 1, 5):
        a = np.percentile(tau_fr[:, 0, i], [50, 25, 75])
        b = np.percentile(tau_fr[:, -1, i], [50, 25, 75])
        print(f"  tau^fr from {STATE[i]:<11s} {years[0]:.0f} {a[0]:7.2f} yr "
              f"[{a[1]:.2f},{a[2]:.2f}]   {years[-1]:.0f} {b[0]:7.2f} yr "
              f"[{b[1]:.2f},{b[2]:.2f}]")
    for k in L.FLOW_NAMES:
        a = np.percentile(cnt_fr[k][:, 0, START], [50, 25, 75])
        b = np.percentile(cnt_fr[k][:, -1, START], [50, 25, 75])
        print(f"  {k:<21s} ({L.FLOW_CH2[k]:<14s}) from {STATE[START]}: "
              f"{a[0]:.4f} [{a[1]:.4f},{a[2]:.4f}] -> "
              f"{b[0]:.4f} [{b[1]:.4f},{b[2]:.4f}]")
    pu = L.prob_reaches_use(A)
    a = np.percentile(pu[:, 0, START], [50, 25, 75])
    b = np.percentile(pu[:, -1, START], [50, 25, 75])
    cond0 = cnt_fr["use_entry"][:, 0, START] / pu[:, 0, START]
    cond1 = cnt_fr["use_entry"][:, -1, START] / pu[:, -1, START]
    print(f"  P^use (Ch2 Eq. prob_use_appendix) from {STATE[START]}: "
          f"{a[0]:.4f} [{a[1]:.4f},{a[2]:.4f}] -> "
          f"{b[0]:.4f} [{b[1]:.4f},{b[2]:.4f}]")
    print(f"  conditional use episodes upsilon_1/P^use "
          f"(Ch2 Eq. conditional_use_appendix): "
          f"{np.median(cond0):.4f} -> {np.median(cond1):.4f}")

    # --- non-autonomous -----------------------------------------------------
    print(f"\n--- non-autonomous (Ch2 Eq. nonautonomous_lifetime / "
          f"_use_count), n_sub = {args.n_sub}/yr ---")
    nonauto = {}
    for rule in L.RULES:
        r = L.nonautonomous_indicators(P, years, rule=rule, n_sub=args.n_sub)
        nonauto[rule] = r
        ns = int(r["end_stable"].sum())
        print(f"  {rule:<8s} t_switch {r['t_switch']:.0f}  "
              f"{r['n_steps']} substeps  closed-form tail carries "
              f"{100*np.median(r['tail_share_tau'][:, 0, START]):.1f}% of "
              f"tau_1({years[0]:.0f})   terminal system asymptotically "
              f"stable for {ns}/{S} seeds")
        if ns < S:
            bad = seeds[~r["end_stable"]]
            print(f"    !! seeds {bad.tolist()} lose their absorbing boundary "
                  f"under this rule (tau_waelz and tau_ref clip at their\n"
                  f"       feasible bounds, so the stock has no exit): the "
                  f"lifetime genuinely diverges and is reported as NaN, not "
                  f"suppressed.")

    # --- validation ---------------------------------------------------------
    print("\n--- validation ---")
    r_hi = L.nonautonomous_indicators(P, years, rule=REF_RULE,
                                      n_sub=2 * args.n_sub)
    rel_h = float(np.nanmax(np.abs(nonauto[REF_RULE]["tau"] - r_hi["tau"]))
                  / np.nanmax(np.abs(r_hi["tau"])))
    print(f"  step halving {args.n_sub} -> {2*args.n_sub}/yr: max rel change "
          f"in tau {rel_h:.2e}  (2nd-order scheme, so the error at "
          f"{2*args.n_sub}/yr is ~{rel_h/3:.1e})")
    term = float(np.max(np.abs(nonauto["hold"]["tau"][:, -1] - tau_fr[:, -1])))
    term_u = float(np.max(np.abs(
        nonauto["hold"]["counts"]["use_entry"][:, -1]
        - cnt_fr["use_entry"][:, -1])))
    print(f"  terminal-node identity under `hold` (A is constant beyond "
          f"{years[-1]:.0f}, so the two forms must coincide at "
          f"t_0 = {years[-1]:.0f}):")
    print(f"    max |tau_nonauto - tau^fr| = {term:.3e};  "
          f"max |upsilon - upsilon^fr| = {term_u:.3e}   (exact answer 0)")
    ref_rows = []
    for si, ti in ((0, 0), (0, 20), (17, 5), (34, 30)):
        tref, cref = reference_integration(P, years, si, ti)
        e_t = float(np.max(np.abs(tref - nonauto[REF_RULE]["tau"][si, ti])))
        e_c = float(np.max(np.abs(
            cref["use_entry"] - nonauto[REF_RULE]["counts"]["use_entry"][si, ti])))
        ref_rows.append(dict(seed=int(seeds[si]), year=float(years[ti]),
                             max_abs_err_tau=e_t, max_abs_err_upsilon=e_c,
                             rel_err_tau=e_t / float(np.abs(tref).max())))
        print(f"  vs LSODA reference (rtol 1e-11) seed {seeds[si]} "
              f"t0 {years[ti]:.0f}: max |dtau| = {e_t:.2e} yr "
              f"({100*e_t/np.abs(tref).max():.4f}%), "
              f"max |dupsilon| = {e_c:.2e}")
    pd.DataFrame(
        [dict(check="step_halving_max_rel_change_tau", value=rel_h),
         dict(check="terminal_identity_max_abs_tau", value=term),
         dict(check="terminal_identity_max_abs_upsilon", value=term_u),
         dict(check="min_N_entry_frozen", value=float(N.min())),
         dict(check="max_spectral_abscissa_in_window",
              value=float(L.spectral_abscissa(A).max()))]
        + [dict(check=f"reference_lsoda_seed{r['seed']}_y{int(r['year'])}"
                      f"_max_abs_err_tau", value=r["max_abs_err_tau"])
           for r in ref_rows]).to_csv(
        os.path.join(args.out, "wp2d_validation.csv"), index=False)

    # --- the headline: the discrepancy --------------------------------------
    disc = discrepancy_table(frozen, nonauto, years)
    print("\n=== the frozen-time approximation error "
          "(non-autonomous - frozen, seed-paired HL) ===")
    for ind, lab in (("tau_FD", "technological lifetime  tau_FD,1  (yr)"),
                     ("use_entry", "expected use count      upsilon_1")):
        sub = disc[(disc.indicator == ind) & (disc.rule == REF_RULE)
                   & (disc.start_stock == STATE[START])]
        print(f"  {lab}")
        for y in (years[0], years[len(years) // 2], years[-1]):
            r = sub[sub.year == y].iloc[0]
            print(f"    {y:.0f}  frozen {r.frozen_median:8.4f}   "
                  f"non-aut. {r.nonauto_median:8.4f}   "
                  f"diff {r.abs_diff_hl:+8.4f} "
                  f"[{r.abs_diff_lo:+.4f},{r.abs_diff_hi:+.4f}]   "
                  f"{100*r.rel_diff_hl:+6.2f}% "
                  f"[{100*r.rel_diff_lo:+.2f},{100*r.rel_diff_hi:+.2f}]")
        tr = sub[sub.year <= years[-1] - 10]
        print(f"    mean |relative error| over t0 <= {years[-1]-10:.0f}: "
              f"{100*np.abs(tr.rel_diff_hl).mean():.2f}%   "
              f"max {100*np.abs(tr.rel_diff_hl).max():.2f}%")

    print(f"\n  all indicators, |relative error| of the frozen form under "
          f"`{REF_RULE}`, over t0 <= {years[-1]-10:.0f}:")
    for ind in ["tau_FD"] + L.FLOW_NAMES:
        sub = disc[(disc.indicator == ind) & (disc.rule == REF_RULE)
                   & (disc.start_stock == STATE[START])
                   & (disc.year <= years[-1] - 10)]
        print(f"    {ind:<21s} mean {100*np.abs(sub.rel_diff_hl).mean():6.2f}%"
              f"   max {100*np.abs(sub.rel_diff_hl).max():6.2f}%"
              f"   sign {'+' if (sub.rel_diff_hl > 0).all() else 'mixed'}")

    print("\n  the two old-scrap routes (Ch2 Eq. old_scrap_count_appendix):")
    for k in ("oldscrap_manufacture", "oldscrap_metallurgy"):
        sub = disc[(disc.indicator == k) & (disc.rule == REF_RULE)
                   & (disc.start_stock == STATE[START])]
        r0 = sub[sub.year == years[0]].iloc[0]
        print(f"    {k:<21s} ({L.FLOW_CH2[k]}) {years[0]:.0f}: frozen "
              f"{r0.frozen_median:.4f} -> non-aut. {r0.nonauto_median:.4f}  "
              f"({100*r0.rel_diff_hl:+.2f}% "
              f"[{100*r0.rel_diff_lo:+.2f},{100*r0.rel_diff_hi:+.2f}])")

    # --- sensitivity to the extrapolation rule ------------------------------
    print("\n--- sensitivity to the extrapolation rule (spec: 'document it "
          "and test sensitivity to the choice') ---")
    rule_rows = []
    all_arrs = [("tau_FD", {r: v["tau"] for r, v in nonauto.items()})]
    all_arrs += [(k, {r: v["counts"][k] for r, v in nonauto.items()})
                 for k in L.FLOW_NAMES]
    for ind, arrs in all_arrs:
        for ti, y in enumerate(years):
            vals = {r: float(np.nanmedian(v[:, ti, START]))
                    for r, v in arrs.items()}
            spread = max(vals.values()) - min(vals.values())
            base = vals[REF_RULE]
            rule_rows.append(dict(indicator=ind, year=float(y),
                                  spread_abs=spread, spread_rel=spread / base,
                                  **{f"median_{r}": v for r, v in vals.items()}))
        rr = pd.DataFrame([r for r in rule_rows if r["indicator"] == ind])
        print(f"  {ind:<21s} across-rule spread of the seed median, as a "
              f"fraction of `{REF_RULE}`: median "
              f"{100*rr.spread_rel.median():5.2f}%, max "
              f"{100*rr.spread_rel.max():5.2f}% (in "
              f"{int(rr.loc[rr.spread_rel.idxmax(), 'year'])})")

    # Is the frozen-vs-non-autonomous gap larger than the ambiguity in the
    # extrapolation rule?  If not, the discrepancy is not reportable.
    print(f"\n  discrepancy vs rule ambiguity, at t0 = {years[0]:.0f}, from "
          f"{STATE[START]}:")
    print(f"    {'indicator':<21s} {'rule':<9s} {'frozen':>9s} "
          f"{'non-aut.':>9s} {'rel diff':>10s}")
    for ind, _ in all_arrs:
        for rule in L.RULES:
            r = disc[(disc.indicator == ind) & (disc.rule == rule)
                     & (disc.start_stock == STATE[START])
                     & (disc.year == years[0])].iloc[0]
            print(f"    {ind if rule == L.RULES[0] else '':<21s} {rule:<9s} "
                  f"{r.frozen_median:9.4f} {r.nonauto_median:9.4f} "
                  f"{100*r.rel_diff_hl:+9.2f}%")
    pd.DataFrame(rule_rows).to_csv(
        os.path.join(args.out, "wp2d_rule_sensitivity.csv"), index=False)

    # --- elasticities  (Ch2 Eq. tau_U_elasticities) -------------------------
    dA = L.dA_dparams(P)
    el_rows = []
    dtau, dcounts, _ = L.indicator_sensitivity(A, dA)
    tau_v, cnt_v, _ = L.frozen_indicators(A)
    for n in range(L.N_PARAM):
        for i in range(6):
            for ti, y in enumerate(years):
                p = P[:, ti, n]
                def stats(dv, v):
                    e = p * dv / np.where(np.abs(v) > 0, v, np.nan)
                    q = np.nanpercentile(e, [25, 50, 75])
                    dq = np.nanpercentile(dv, [25, 50, 75])
                    return dict(elasticity_median=q[1], elasticity_q1=q[0],
                                elasticity_q3=q[2], derivative_median=dq[1],
                                derivative_q1=dq[0], derivative_q3=dq[2])
                el_rows.append(dict(indicator="tau_FD",
                                    param=L.PARAM_NAMES[n],
                                    start_stock=STATE[i], year=float(y),
                                    **stats(dtau[:, ti, n, i], tau_v[:, ti, i])))
                for k in L.FLOW_NAMES:
                    el_rows.append(dict(indicator=k, param=L.PARAM_NAMES[n],
                                        start_stock=STATE[i], year=float(y),
                                        **stats(dcounts[k][:, ti, n, i],
                                                cnt_v[k][:, ti, i])))
    el = pd.DataFrame(el_rows)
    print("\n--- elasticities S_tau,l and S_upsilon,l "
          "(Ch2 Eq. tau_U_elasticities), from S_conc, 2019 ---")
    for ind, lab in (("tau_FD", "S_tau,l "), ("use_entry", "S_ups,l")):
        sub = el[(el.indicator == ind) & (el.start_stock == STATE[START])
                 & (el.year == years[-1])]
        top = sub.reindex(sub.elasticity_median.abs().sort_values(
            ascending=False).index)[:6]
        for _, r in top.iterrows():
            print(f"  {lab} {r.param:<16s} {r.elasticity_median:+8.4f} "
                  f"[{r.elasticity_q1:+.4f},{r.elasticity_q3:+.4f}]")

    # --- conditioning: the frozen form is also noisier ----------------------
    # A second, unforced consequence of reading the frozen form: it evaluates
    # a whole absorption horizon at one year's coefficients, so year-on-year
    # jitter in the fitted coefficients passes straight through, while the
    # non-autonomous form integrates over the future path and averages it out.
    print("\n--- conditioning of the two forms ---")
    cond_rows = []
    for ind, fr, na in (("tau_FD", tau_fr[:, :, START],
                         nonauto[REF_RULE]["tau"][:, :, START]),
                        ("use_entry", cnt_fr["use_entry"][:, :, START],
                         nonauto[REF_RULE]["counts"]["use_entry"][:, :, START])):
        ra = np.abs(np.diff(fr, axis=1)).mean(1) / np.abs(fr).mean(1)
        rb = np.abs(np.diff(na, axis=1)).mean(1) / np.abs(na).mean(1)
        h = L.hodges_lehmann(ra - rb)
        cond_rows.append(dict(indicator=ind,
                              roughness_frozen=float(np.median(ra)),
                              roughness_nonautonomous=float(np.median(rb)),
                              ratio=float(np.median(ra / rb)),
                              hl=h["hl"], lo=h["lo"], hi=h["hi"]))
        print(f"  {ind:<10s} mean |year-on-year| / mean level: frozen "
              f"{100*np.median(ra):5.2f}%   non-autonomous "
              f"{100*np.median(rb):5.2f}%   ratio {np.median(ra/rb):.2f}x  "
              f"(HL {100*h['hl']:+.2f} pp [{100*h['lo']:+.2f},"
              f"{100*h['hi']:+.2f}])")
    pd.DataFrame(cond_rows).to_csv(
        os.path.join(args.out, "wp2d_conditioning.csv"), index=False)

    # --- Chapter 2's alpha_13 vs alpha_14 ranking, tested -------------------
    # Ch2 (Sec. tab:tau_U_sensitivities) states: "Increasing old-scrap returns
    # through alpha_13 and alpha_14 raises both indicators, with the return to
    # metallurgy having the stronger normalised effect in the current
    # parameterisation."  That parameterisation is copper and assumed; this is
    # the first empirical test of the ranking.
    #
    # The unconstrained partials are the wrong test.  In the UDE the loss on
    # each old-scrap route is a fixed share of that same route's flow
    # ((1 - tau_waelz) on the metallurgy route, the manufacturing loss share
    # on the direct-reuse route), and there is no landfill state to divert
    # material away from (mapping decision 1).  Raising a gross rate therefore
    # raises return and loss together.  The well-posed question is the
    # *split*: Ch2's own directional-derivative device, applied to the two
    # routes out of S_scrap at a fixed combined rate.
    print("\n=== Ch2's alpha_13 vs alpha_14 ranking, tested on the "
          "estimated A(t) ===")
    nd = L.PARAM_NAMES.index("alpha_dr")
    nw = L.PARAM_NAMES.index("alpha_win")
    ch2_rows = []
    for ti, y in ((0, years[0]), (T - 1, years[-1])):
        tot = P[:, ti, nw] + P[:, ti, nd]
        for ind, dv, v in (("tau_FD", dtau[:, ti, :, START], tau_fr[:, ti, START]),
                           ("use_entry", dcounts["use_entry"][:, ti, :, START],
                            cnt_fr["use_entry"][:, ti, START])):
            step = 0.01 * tot                    # +1% of the combined rate
            h = L.hodges_lehmann((dv[:, nw] - dv[:, nd]) * step)
            hr = L.hodges_lehmann((dv[:, nw] - dv[:, nd]) * step / v)
            ch2_rows.append(dict(
                year=float(y), indicator=ind,
                direction="alpha_win <- alpha_dr (metallurgy <- direct reuse)",
                d_indicator_hl=h["hl"], d_indicator_lo=h["lo"],
                d_indicator_hi=h["hi"], rel_hl=hr["hl"], rel_lo=hr["lo"],
                rel_hi=hr["hi"],
                ch2_prediction="metallurgy stronger => positive",
                holds=bool(hr["lo"] > 0)))
            print(f"  {y:.0f}  shift 1% of (alpha_win + alpha_dr) from direct "
                  f"reuse to metallurgy:")
            print(f"        d {ind:<10s} = {h['hl']:+.6f} "
                  f"[{h['lo']:+.6f}, {h['hi']:+.6f}]   "
                  f"({100*hr['hl']:+.4f}% [{100*hr['lo']:+.4f},"
                  f"{100*hr['hi']:+.4f}])")
    pd.DataFrame(ch2_rows).to_csv(
        os.path.join(args.out, "wp2d_ch2_route_ranking.csv"), index=False)
    verdict = "FAILS" if all(r["rel_hi"] < 0 for r in ch2_rows) else (
        "HOLDS" if all(r["rel_lo"] > 0 for r in ch2_rows) else "MIXED")
    print(f"  Ch2's ranking (metallurgy stronger than direct reuse): "
          f"**{verdict}** on the estimated zinc A(t) at both ends of the "
          f"window.")
    print(f"  Direct reuse is the stronger route: the metallurgy route loses "
          f"(1 - tau_waelz) = "
          f"{100*(1-np.median(P[:, 0, 5])):.0f}% ({years[0]:.0f}) / "
          f"{100*(1-np.median(P[:, -1, 5])):.0f}% ({years[-1]:.0f}) of its "
          f"flow and\n  re-enters at Refined, so the returned material pays "
          f"the manufacturing loss a second time.")

    # --- persist ------------------------------------------------------------
    os.makedirs(args.out, exist_ok=True)
    indicator_table(frozen, nonauto, years, seeds).to_csv(
        os.path.join(args.out, "wp2d_indicators.csv"), index=False)
    disc.to_csv(os.path.join(args.out, "wp2d_discrepancy.csv"), index=False)
    el.to_csv(os.path.join(args.out, "wp2d_elasticities.csv"), index=False)

    arrays = dict(years=years, seeds=seeds, mu_cohorts=mu,
                  state_names=np.array(STATE, object),
                  flow_names=np.array(L.FLOW_NAMES, object),
                  param_names=np.array(L.PARAM_NAMES, object),
                  rules=np.array(L.RULES, object),
                  tau_frozen=tau_fr, N_frozen=N,
                  prob_reaches_use=pu,
                  dtau_dparams=dtau,
                  source_md5=np.array(md5), n_sub=np.array(args.n_sub),
                  ref_rule=np.array(REF_RULE, object))
    for k in L.FLOW_NAMES:
        arrays[f"count_frozen_{k}"] = cnt_fr[k]
        arrays[f"dcount_dparams_{k}"] = dcounts[k]
    for rule, v in nonauto.items():
        arrays[f"tau_nonauto_{rule}"] = v["tau"]
        arrays[f"end_stable_{rule}"] = v["end_stable"]
        arrays[f"t_switch_{rule}"] = np.array(v["t_switch"])
        for k in L.FLOW_NAMES:
            arrays[f"count_nonauto_{rule}_{k}"] = v["counts"][k]
    np.savez_compressed(os.path.join(args.out, "wp2d_circularity.npz"),
                        **arrays)

    fig_circularity(frozen, nonauto, years, d["mask_test"],
                    os.path.join(args.out, "wp2d_circularity.png"))
    fig_elasticities(el, years, os.path.join(args.out,
                                             "wp2d_elasticities.png"))
    print(f"\nwrote wp2d_* to {args.out}")
    return 0


