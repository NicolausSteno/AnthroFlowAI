def coeff_path(fit, params, t_grid, S_path=None, data=None):
    """The fitted model's reported coefficients at *arbitrary* times.

    The UDE is a continuous-time model, so `alpha_hat(t)` is defined between
    the annual nodes it was fitted at.  That is exactly what WP-11e's second
    question needs: an annually-fitted model can be *asked* for monthly
    dynamics, and the question is whether what comes back is signal or the
    shape of `exog_fn`'s interpolation.

    Returns `alphas` (T, 4), `tau_sup` (T, 8), `f_cohort` (T, 3), `cp` (T,).
    """
    import jax
    import jax.numpy as jnp

    d = fit.data_all if data is None else data
    t_grid = np.asarray(t_grid, float).ravel()
    if S_path is None:
        S_obs = np.asarray(d["stocks_obs"], float)
        yrs = np.asarray(d["years"], float).ravel()
        S_path = np.column_stack([np.interp(t_grid, yrs, S_obs[:, j])
                                  for j in range(S_obs.shape[1])])
    S_path = np.asarray(S_path, float)

    @jax.jit
    def one(t, Sx):
        ex = __import__("zinc_colloc_v5").exog_fn(t, d["exog_times"],
                                                  d["exog_values"])
        o = fit.nn_eval(params, t, Sx, ex, d)
        tau_sup = jnp.concatenate([o["taus"],
                                   jnp.array([o["frac_fu"][0], o["frac_fu"][1],
                                              o["frac_eu"][0], o["frac_eu"][1]])])
        return o["alphas"], tau_sup, o["f_cohort"], o["cp"]

    A, T8, FC, CP = jax.vmap(one)(jnp.asarray(t_grid), jnp.asarray(S_path))
    return dict(t=t_grid, alphas=np.asarray(A), tau_sup=np.asarray(T8),
                f_cohort=np.asarray(FC), cp=np.asarray(CP))


