def sinc_gain(f, delta):
    """`|sinc(pi f Delta)|` — the boxcar (period-integral) transfer, with
    exact nulls at `f = k/Delta`.  Spec section 1, consequence 3."""
    x = np.pi * np.asarray(f, float) * float(delta)
    return np.abs(np.where(np.abs(x) < 1e-12, 1.0, np.sin(x) / np.where(x == 0, 1.0, x)))


def alias_freq(f, delta):
    """Where a component at `f` lands after point sampling at spacing `Delta`.

    Point sampling has unit gain and no nulls: it *folds* rather than
    annihilates.  A component at exactly `k/Delta` folds to 0 — it becomes a
    constant offset in the sampled series, which is the opposite of what the
    same component does to a period-integrated one.
    """
    f = np.asarray(f, float)
    fs = 1.0 / float(delta)
    r = np.mod(f, fs)
    return np.minimum(r, fs - r)


def project_amplitude(t, y, f, *, t0=0.0):
    """Least-squares amplitude and phase of a single frequency in `y(t)`.

    Phase-safe: an FFT bin only lines up with `f` when `f` is a harmonic of
    the record length, and every non-harmonic frequency in this package is
    chosen precisely because it is not.  Two-column regression instead.
    """
    t = np.asarray(t, float).ravel()
    y = np.asarray(y, float).ravel()
    w = 2.0 * np.pi * float(f) * (t - t0)
    A = np.column_stack([np.ones_like(t), t - t0, np.sin(w), np.cos(w)])
    beta, *_ = np.linalg.lstsq(A, y, rcond=None)
    s, c = beta[2], beta[3]
    return dict(amp=float(np.hypot(s, c)), phase=float(np.arctan2(c, s)),
                level=float(beta[0]), slope=float(beta[1]))


def band_power(t, y, *, f_cut, detrend=True):
    """Share of the variance of `y(t)` above `f_cut`, on a uniform grid."""
    t = np.asarray(t, float).ravel()
    y = np.asarray(y, float).ravel()
    if detrend:
        A = np.column_stack([np.ones_like(t), t - t[0]])
        beta, *_ = np.linalg.lstsq(A, y, rcond=None)
        y = y - A @ beta
    h = t[1] - t[0]
    n = y.size - 1
    Y = np.fft.rfft(y[:n] - y[:n].mean())
    f = np.fft.rfftfreq(n, d=h)
    p = np.abs(Y) ** 2
    tot = p.sum()
    hi = p[f > f_cut].sum()
    return dict(total=float(tot), above=float(hi),
                share_above=float(hi / max(tot, 1e-30)),
                rms=float(np.std(y)))


# ===========================================================================
# 4. the alpha-target bias, decomposed into its two mechanisms
# ===========================================================================
# WP-11f asks for the bias surface with the two mechanisms separated:
#
#   (i)  **attenuation.**  The period integral is a boxcar, so what the data
#        can report about a sub-annual component is `|sinc(pi f Delta)|` times
#        its true amplitude.  For a *log*-additive oscillation this is not
#        only a loss of amplitude: the window mean of `A exp(a sin)` exceeds
#        `A exp(mean(a sin))` by the Jensen gap, exactly `log I_0(a)` over a
#        whole number of cycles, so annual observation of an oscillating
#        coefficient reports a level that is biased *upward* by `~a^2/4`
#        regardless of frequency.  That is a bias, not a variance.
#
#   (ii) **target construction.**  `alpha_obs = F_int / trapz(S)` is an
#        integral over an interpolated point stock, which introduces the
#        within-window `Cov_w(alpha, S)/mean_w(S)` term and a trapezoid
#        quadrature term.  WP-3 established the identity; this reuses it.
#
# Both are measured against the same reference so they add.
def jensen_log_bias(a):
    """`log I_0(a)`: the exact log-level bias of a full-cycle average of
    `exp(a sin)`.  `~a^2/4` for small `a`."""
    from numpy import i0
    return np.log(i0(np.asarray(a, float)))


def bias_cell(ctx, *, freq, amp, phase, delta=1.0, channels=None,
              arm_name="base", dense=None):
    """One cell of the WP-11f surface: all four channels driven at `(freq,
    amp, phase)`, observed at window width `delta`.

    Returns, per channel and in log units so the components add:

      `attenuation`  log(window-mean alpha) - log(alpha_true at the node)
                     — what period integration does to the reported level,
                     including the Jensen gap and the year-end placement;
      `covariance`   log(exposure-weighted mean) - log(unweighted mean)
                     — the within-window F-S covariance term;
      `quadrature`   log(alpha_obs) - log(exposure-weighted mean)
                     — the trapezoid stock exposure;
      `total`        log(alpha_obs) - log(alpha_true at the node).

    Driving all four channels in one solve rather than one at a time follows
    `run_wp3.part2b_amplitude_sweep`.  The channels then share a perturbed
    trajectory, so a small cross-channel term is folded into each cell; it is
    second order in `amp` and `check()` bounds it.
    """
    chans = list(ALPHA_NAMES if channels is None else channels)
    season = [(c, float(freq), float(amp), float(phase)) for c in chans]
    if dense is None:
        dense = S.dense_solve(ctx, arm_name, season=season)
    b = S.alpha_target_bias(ctx, dense, delta, arm_name=arm_name, season=season)

    # alpha_true at the node the model is supervised at: the closing year of
    # the window (`_build_empirical_alphas` stores the window average at the
    # closing year — WP-3's "year-end placement" finding).
    idx = S._window_indices(dense, delta)
    tc = S.truth_coefficients(ctx, dense["t"][idx[1:]], arm_name,
                              S_path=dense["S4"][idx[1:]], season=season)
    a_node = tc["alphas"]                                   # (nW, 4)

    lg = lambda x: np.log(np.maximum(np.asarray(x, float), 1e-30))
    out = {}
    for k, name in enumerate(ALPHA_NAMES):
        att = lg(b["a_unweighted"][:, k]) - lg(a_node[:, k])
        cov = lg(b["a_weighted"][:, k]) - lg(b["a_unweighted"][:, k])
        quad = lg(b["a_obs"][:, k]) - lg(b["a_weighted"][:, k])
        tot = lg(b["a_obs"][:, k]) - lg(a_node[:, k])
        out[name] = dict(attenuation=att, covariance=cov, quadrature=quad,
                         total=tot, years=b["years"])
    return out, dense


