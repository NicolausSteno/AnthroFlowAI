#!/usr/bin/env python3
"""
run_wp2d.py — WP-2d: circularity indicators, frozen-time vs non-autonomous
==========================================================================

The highest-value result in WP-2, and the one Chapter 2 poses but cannot
evaluate.  On the estimated A(t) of WP-2a, both forms of Chapter 2's
circularity indicators are computed at every year node and every seed, and the
**discrepancy between them is reported** — which quantifies the frozen-time
approximation error and is a methodological contribution back to Chapter 2,
possible only because Chapter 4 supplies an empirical A(t).

Frozen-time                                  # Ch2 Eq. frozen_time_circularity
    tau^fr_i(t)     = 1^T [-A_FD(t)]^-1 e_i
    upsilon^fr_i(t) = c_use(t)^T [-A_FD(t)]^-1 e_i

Non-autonomous, Phi(t0+u, t0) generated by the fitted A_FD(t)
                                             # Ch2 Eq. nonautonomous_lifetime
    tau_FD,i(t0)    = int_0^inf 1^T Phi(t0+u, t0) e_i du
                                             # Ch2 Eq. nonautonomous_use_count
    upsilon_i(t0)   = int_0^inf c_use(t0+u)^T Phi(t0+u, t0) e_i du

with `A_FD(t) = A(t)` and `alpha_8 e_3^T -> c_use(t)^T` as set out in
`zinc_circ_lab` (the UDE has no landfill state, and entry into use is fed by
two stocks because Chapter 2's s_2 and s_3 are aggregated).  The same pair is
computed for the two old-scrap return routes, Chapter 2's `Upsilon_13` and
`Upsilon_14` (Eq. old_scrap_count_appendix) — i.e. for `alpha_dr` and
`alpha_win`, the coefficients the whole circularity argument rests on.

Elasticities `S_tau,l` and `S_upsilon,l` (Ch2 Eq. tau_U_elasticities) are
reported alongside; the full sensitivity matrices behind them are WP-2e.

Coefficients beyond the sample window
-------------------------------------
`Phi` needs A(t) over the whole absorption horizon, so a rule is required.
Four are run and compared (`zinc_circ_lab.coeff_path`):
  `hold`     freeze at the 2019 node — the reference rule;
  `mean5`    freeze at the mean of the last five nodes;
  `trend20`  continue the fitted 10-year trend for 20 yr, then freeze;
  `trend50`  the same for 50 yr — a deliberate stress test.
Beyond `t_switch` every rule is constant, so the infinite tail is closed in
**closed form** (`c^T N_const Phi(t_switch)`) rather than truncated.  The
sensitivity of every reported number to the choice is in
`wp2d_rule_sensitivity.csv`.

    python run_wp2d.py --check
    python run_wp2d.py
"""

